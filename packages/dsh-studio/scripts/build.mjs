import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const libDir = path.join(root, "lib");
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

await mkdir(libDir, { recursive: true });

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "src/host/index.ts")],
  outfile: path.join(libDir, "index.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  sourcemap: false,
  legalComments: "none",
  external: ["@deepseek-ai/*"],
  logLevel: "info",
});

// Internal builds for the Node test suite. They are not part of the public exports.
await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "src/host/store.ts")],
  outfile: path.join(libDir, "store.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  sourcemap: false,
  legalComments: "none",
  logLevel: "info",
});

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "src/host/workspace.ts")],
  outfile: path.join(libDir, "workspace.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  sourcemap: false,
  legalComments: "none",
  logLevel: "info",
});

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "src/host/verify.ts")],
  outfile: path.join(libDir, "verify.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  sourcemap: false,
  legalComments: "none",
  logLevel: "info",
});

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "src/host/docs.ts")],
  outfile: path.join(libDir, "docs.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  sourcemap: false,
  legalComments: "none",
  logLevel: "info",
});

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "src/host/compat.ts")],
  outfile: path.join(libDir, "compat.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  sourcemap: false,
  legalComments: "none",
  external: ["@deepseek-ai/*"],
  logLevel: "info",
});

const client = await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "src/client/index.tsx")],
  bundle: true,
  platform: "browser",
  format: "cjs",
  target: "chrome120",
  jsx: "automatic",
  sourcemap: false,
  legalComments: "none",
  external: ["react", "react/jsx-runtime", "react-dom", "react-dom/client"],
  write: false,
  logLevel: "info",
});

const clientCode = client.outputFiles?.[0]?.text;
if (clientCode === undefined || clientCode.trim() === "") {
  throw new Error("client bundle is empty");
}

const wrapped = `/* Generated by scripts/build.mjs — do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${clientCode}
    return module.exports;
  }
});
`;

await writeFile(path.join(libDir, "client.js"), wrapped, "utf8");

console.log(
  `built ${pkg.name}@${pkg.version}: lib/index.js + lib/client.js (${String(
    Buffer.byteLength(wrapped),
  )} bytes client)`,
);
